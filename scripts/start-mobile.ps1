#Requires -Version 5.1
<#
.SYNOPSIS
    Start the JARVIS backend over HTTPS on the LAN so the Android app can connect.

.DESCRIPTION
    The Android app refuses cleartext HTTP and requires an https:// backend for
    chat, pairing and Live Voice. This script:

      1. Locates this machine's LAN IPv4 address.
      2. Ensures a self-signed certificate covering that IP exists in data\tls
         (generated by scripts/generate_https_cert.py; a CA the phone trusts
         after a one-time install of data\tls\jarvis-ca.crt).
      3. Adds (or reports) the inbound firewall rule for TCP 8443.
      4. Starts uvicorn with TLS bound to the LAN IP on port 8443.

    The plain-HTTP browser UI on 127.0.0.1:8000 is untouched; this is a
    second, phone-facing listener. Stop with Ctrl+C.

.PARAMETER Port
    HTTPS port for the phone-facing listener (default 8443).

.PARAMETER ForceCert
    Regenerate the certificate even if the existing one is still valid.

.PARAMETER SkipFirewall
    Do not attempt to create the firewall rule.

.EXAMPLE
    .\scripts\start-mobile.ps1
    # Serve https://<lan-ip>:8443 for the Android app.

.EXAMPLE
    .\scripts\start-mobile.ps1 -ForceCert
    # After an IP change, mint a fresh certificate (reinstall it on the phone).
#>
[CmdletBinding()]
param(
    [ValidateRange(1, 65535)]
    [int]$Port = 8443,
    [switch]$ForceCert,
    [switch]$SkipFirewall
)

$ErrorActionPreference = "Stop"

. (Join-Path $PSScriptRoot "mobile-common.ps1")

$root = Get-JarvisRepoRoot
$python = Test-JarvisVenv -Root $root

if (-not (Test-Path (Join-Path $root ".env"))) {
    throw ".env missing at $root. Run INSTALL_JARVIS.bat or scripts\setup-windows.ps1 first."
}

Write-Host ""
Write-Host "JARVIS Mobile - HTTPS backend for the Android app" -ForegroundColor Cyan
Write-Host "==================================================" -ForegroundColor Cyan

# ------------------------------------------------------------------- 1. network
$lanIp = Get-JarvisLanIPv4
Write-Host "[PASS] LAN IP: $lanIp" -ForegroundColor Green
$baseUrl = Get-JarvisMobileUrl -LanIp $lanIp -Port $Port

# --------------------------------------------------------------- 2. certificate
$certInfo = New-JarvisHttpsCert -LanIp $lanIp -Force:$ForceCert
Write-Host "[PASS] Certificate: $($certInfo.Cert)" -ForegroundColor Green

# ------------------------------------------------------------------ 3. firewall
if (-not $SkipFirewall) {
    Add-JarvisFirewallRule -Port $Port | Out-Null
}

# ------------------------------------------------------------- 4. print handoff
# Print the backend URL before the blocking server start; never print credentials.
# on first run, while uvicorn keeps the window open below.
Write-Host ""
Write-Host "Phone connection details" -ForegroundColor Cyan
Write-Host "  Backend URL : $baseUrl"
Write-Host "  Pairing token: not displayed (secret protection)" -ForegroundColor Green
Write-Host "  Copy JARVIS_API_TOKEN from your local .env file when pairing." -ForegroundColor Yellow
Write-Host ""
Write-Host "On the phone:" -ForegroundColor Green
Write-Host "  1. Install the APK (scripts\setup-android.ps1 -Install, or copy the apk)."
Write-Host "  2. One-time: install this CA certificate on the phone:" -ForegroundColor Yellow
Write-Host "     $($certInfo.CaCopy)" -ForegroundColor Yellow
Write-Host "     (Settings > Security > Encryption & credentials > Install a certificate >"
Write-Host "      CA certificate). Without it the app rejects the self-signed server cert."
Write-Host "  3. Open JARVIS > enter the backend URL and copy JARVIS_API_TOKEN from .env > Pair > Connect."
Write-Host ""
Write-Host "Security: TLS + bearer token on a private LAN only. Never port-forward 8443" -ForegroundColor DarkGray
Write-Host "or expose it to the public internet; this prototype has no public hardening." -ForegroundColor DarkGray

# ------------------------------------------------------------------- 5. already up?
if (Test-JarvisBackendHealth -Url $baseUrl) {
    Write-Host ""
    Write-Host "[PASS] A JARVIS HTTPS backend is already responding at $baseUrl" -ForegroundColor Green
    Write-Host "       (another instance owns port $Port; not starting a second one.)" -ForegroundColor Yellow
    exit 0
}

# ---------------------------------------------------------------------- 6. start
Write-Host ""
Write-Host "Starting HTTPS backend at $baseUrl ..." -ForegroundColor Cyan
Write-Host "Stop with Ctrl+C." -ForegroundColor DarkGray

$sslArgs = @(
    "-m", "uvicorn", "app.main_enhanced:app",
    "--host", $lanIp,
    "--port", "$Port",
    "--ssl-certfile", $certInfo.Cert,
    "--ssl-keyfile", $certInfo.Key,
    "--log-level", "info"
)
Push-Location $root
try {
    & $python @sslArgs
    $exitCode = $LASTEXITCODE
} finally {
    Pop-Location
}
if ($exitCode -ne 0) {
    throw "HTTPS backend exited with code $exitCode. Check the log output above."
}
exit 0
